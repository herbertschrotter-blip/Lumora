/// <summary>Temporärer „Container“ mit einer nachgebauten ComfyUI-Installation unter <c>.lumora-ki</c> (keine echten Programme).</summary>
internal sealed class FakeContainer : IDisposable
{
    public FakeContainer(string version = "0.43.0", bool withManifest = true, params string[] extensions)
    {
        Root = Path.Combine(Path.GetTempPath(), "Lumora.Tests", "ki-" + Guid.NewGuid().ToString("N"));
        Layout = new AiEditLayout(Root);
        Directory.CreateDirectory(Path.GetDirectoryName(Layout.PythonExe)!);
        File.WriteAllText(Layout.PythonExe, string.Empty);
        Directory.CreateDirectory(Layout.ComfyRoot);
        File.WriteAllText(Layout.MainPy, "# main");
        File.WriteAllText(Layout.VersionFile, $"# This file is automatically generated by the build process when version is\n__version__ = \"{version}\"\n");
        foreach (var extension in extensions)
        {
            Directory.CreateDirectory(Path.Combine(Layout.CustomNodesRoot, extension));
        }

        if (withManifest)
        {
            var manifest = new AiInstallManifest
            {
                ComfyUi = new AiInstallPackage(version),
                Extensions = extensions.Select(e => new AiInstallExtension(e, Commit: "6ea2651e7df66d7585f6ffee804b20e92fb38b8a")).ToList(),
                Models = [new AiInstallModel("vae/ae.safetensors", "Text-Encoder, VAE", Bytes: 3)],
            };
            File.WriteAllText(Layout.InstallFile, manifest.ToJson());
        }
    }

    public string Root { get; }

    public AiEditLayout Layout { get; }

    public void Dispose()
    {
        try
        {
            Directory.Delete(Root, recursive: true);
        }
        catch (IOException)
        {
        }
    }
}

/// <summary>Prozess-Attrappe: läuft, bis <see cref="KillTree"/> oder <see cref="Exit"/> kommt.</summary>
internal sealed class FakeComfyProcess : IComfyProcess
{
    private readonly TaskCompletionSource _exited = new(TaskCreationOptions.RunContinuationsAsynchronously);

    public bool HasExited => _exited.Task.IsCompleted;

    public int? ExitCode { get; private set; }

    public int KillCount { get; private set; }

    public bool Disposed { get; private set; }

    public Task WaitForExitAsync(CancellationToken ct) => _exited.Task.WaitAsync(ct);

    public void KillTree()
    {
        KillCount++;
        Exit(1);
    }

    public void Exit(int code)
    {
        ExitCode ??= code;
        _exited.TrySetResult();
    }

    public void Dispose() => Disposed = true;
}

internal sealed class FakeLauncher : IComfyProcessLauncher
{
    public List<ProcessStartInfo> Starts { get; } = new();

    public List<FakeComfyProcess> Processes { get; } = new();

    /// <summary>Beim Start eine Datei in die Ausgabe legen (prüft das Leeren beim Beenden).</summary>
    public string? WriteOutputFile { get; set; }

    public bool ExitImmediately { get; set; }

    public IComfyProcess Start(ProcessStartInfo startInfo, Action<string> onOutput)
    {
        Starts.Add(startInfo);
        var process = new FakeComfyProcess();
        Processes.Add(process);
        onOutput(@"Setting output directory to: C:\geheim\pfad\output");
        if (WriteOutputFile is { } file)
        {
            File.WriteAllText(file, "x");
        }

        if (ExitImmediately)
        {
            process.Exit(3);
        }

        return process;
    }
}

/// <summary>HTTP-Attrappe für <c>/system_stats</c> und <c>/interrupt</c>.</summary>
internal sealed class FakeComfyHandler : HttpMessageHandler
{
    public string Version { get; set; } = "0.43.0";

    public string DeviceType { get; set; } = "cuda";

    /// <summary>So viele Abfragen schlagen fehl, bevor der Server „antwortet“ (int.MaxValue = nie).</summary>
    public int FailFirst { get; set; }

    public int StatsCalls;

    public int InterruptCalls;

    protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken)
    {
        var path = request.RequestUri!.AbsolutePath;
        if (path.EndsWith("/system_stats", StringComparison.Ordinal))
        {
            if (Interlocked.Increment(ref StatsCalls) <= FailFirst)
            {
                throw new HttpRequestException("Verbindung abgelehnt");
            }

            var json = $$"""
                {"system":{"os":"win32","comfyui_version":"{{Version}}"},
                 "devices":[{"name":"cuda:0 NVIDIA GeForce GTX 1080 Ti : cudaMallocAsync","type":"{{DeviceType}}","index":0,"vram_total":11810832384,"vram_free":11000000000}]}
                """;
            return Task.FromResult(new HttpResponseMessage(HttpStatusCode.OK) { Content = new StringContent(json, Encoding.UTF8, "application/json") });
        }

        if (path.EndsWith("/interrupt", StringComparison.Ordinal) && request.Method == HttpMethod.Post)
        {
            Interlocked.Increment(ref InterruptCalls);
            return Task.FromResult(new HttpResponseMessage(HttpStatusCode.OK));
        }

        return Task.FromResult(new HttpResponseMessage(HttpStatusCode.NotFound));
    }
}

internal static class AiEditWait
{
    public static async Task UntilAsync(Func<bool> condition, int timeoutMs = 5000)
    {
        var watch = Stopwatch.StartNew();
        while (!condition())
        {
            if (watch.ElapsedMilliseconds > timeoutMs)
            {
                throw new TimeoutException("Bedingung nicht erreicht.");
            }

            await Task.Delay(10);
        }
    }
}
